/**
 * Generates `src/icons/phosphor.g.ts`: the icon glyphs the React package uses,
 * as raw SVG strings with the colour left as a `__COLOR__` placeholder.
 *
 * Why generate instead of importing `@phosphor-icons/react`: that package is a
 * DOM React component library, and Lynx renders SVG through
 * `<svg content={string}>`. The SVGs come from `@phosphor-icons/core`, the same
 * artwork the React components wrap, so a ported component draws the identical
 * path.
 *
 * Sources of truth: the imports in `packages/react/src/**\/*.tsx` decide which
 * icons the components need, and the demo site's sources add the ones only a
 * demo uses, because the gallery demos are ports of those same demos. The
 * `weight="..."` props on their JSX usages decide which weights are needed for
 * each icon (default `regular`). Run `bun scripts/generate-icons.ts`.
 *
 * The artwork is `@phosphor-icons/core`, MIT, Copyright (c) 2023 Phosphor Icons
 * (https://github.com/phosphor-icons/core). The generated file carries that
 * notice; keep it when the icons are regenerated.
 */
import { existsSync } from "node:fs";
import { join } from "node:path";

const pkg = `${import.meta.dir}/..`;
const reactSrc = `${pkg}/../react/src`;
const appSrc = `${pkg}/../../apps/site/src`;
const assets = `${pkg}/node_modules/@phosphor-icons/core/assets`;

const WEIGHTS = ["thin", "light", "regular", "bold", "fill", "duotone"] as const;
type Weight = (typeof WEIGHTS)[number];

const HEADER = "// Generated by scripts/generate-icons.ts. Do not edit.";

const weightOf = (value: string): Weight | undefined => WEIGHTS.find((weight) => weight === value);

/** `CaretDown` → `caret-down`, the file stem phosphor uses. */
const kebab = (name: string) =>
  name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();

/** Every source file whose phosphor imports decide the icon set, with its text. */
const reactSources: { file: string; text: string }[] = await Promise.all(
  [reactSrc, appSrc]
    .flatMap((dir) => [...new Bun.Glob("**/*.tsx").scanSync(dir)].map((file) => join(dir, file)))
    .map(async (path) => ({ file: path.slice(pkg.length + 1), text: await Bun.file(path).text() })),
);

/** Icon names imported from `@phosphor-icons/react`, with the files that import them. */
const imported = new Map<string, Set<string>>();
for (const { file, text } of reactSources) {
  for (const match of text.matchAll(/import\s*\{([^}]*)\}\s*from\s*"@phosphor-icons\/react"/g)) {
    for (const raw of match[1].split(",")) {
      const entry = raw.trim();
      // `type Icon` is the component type, not an icon glyph.
      if (!entry || entry.startsWith("type ")) continue;
      const name = entry.split(/\s+as\s+/)[0].trim();
      if (!name) continue;
      const files = imported.get(name) ?? new Set<string>();
      files.add(file);
      imported.set(name, files);
    }
  }
}

/** Weights each icon is drawn with: `regular` plus every `weight="…"` on its JSX usage. */
const weights = new Map<string, Set<Weight>>();
for (const [name] of imported) {
  const used = new Set<Weight>(["regular"]);
  for (const { text } of reactSources) {
    for (const match of text.matchAll(new RegExp(`<${name}\\b[^>]*>`, "g"))) {
      const weight = weightOf(/weight="([a-z]+)"/.exec(match[0])?.[1] ?? "");
      if (weight) used.add(weight);
    }
  }
  weights.set(name, used);
}

/**
 * Reads the glyphs of every icon in one pass: the file list is fixed, so the
 * reads run in parallel and each icon keeps the weights it was found with.
 */
const glyphsOf = new Map<string, { weight: Weight; svg: string }[]>();
const missing: string[] = [];

await Promise.all(
  [...imported.keys()].map(async (name) => {
    const stem = kebab(name);
    const wanted = [...(weights.get(name) ?? new Set<Weight>(["regular"]))].toSorted();
    const glyphs = await Promise.all(
      wanted.map(async (weight) => {
        const file =
          weight === "regular" ? `${assets}/regular/${stem}.svg` : `${assets}/${weight}/${stem}-${weight}.svg`;
        if (!existsSync(file)) return { weight, svg: undefined };
        const svg = (await Bun.file(file).text()).trim().replaceAll("currentColor", "__COLOR__");
        return { weight, svg };
      }),
    );
    const kept: { weight: Weight; svg: string }[] = [];
    for (const glyph of glyphs) {
      if (glyph.svg === undefined) missing.push(`${name} (${glyph.weight})`);
      else kept.push({ weight: glyph.weight, svg: glyph.svg });
    }
    glyphsOf.set(name, kept);
  }),
);

if (missing.length > 0) {
  console.error(`MISSING GLYPHS (${missing.length}):\n  ${missing.toSorted().join("\n  ")}`);
  process.exitCode = 1;
}

const names = [...imported.keys()].toSorted();
const entries = names
  .filter((name) => (glyphsOf.get(name) ?? []).length > 0)
  .map((name) => {
    const glyphs = (glyphsOf.get(name) ?? []).map((glyph) => `    ${glyph.weight}: ${JSON.stringify(glyph.svg)},`);
    return `  ${name}: {\n${glyphs.join("\n")}\n  },`;
  });

const content = `${HEADER}

/**
 * The phosphor glyphs the Horon components draw, keyed by the React component
 * name (\`CaretDown\`), then by weight. Each value is the SVG source with
 * \`__COLOR__\` where the fill was \`currentColor\`; \`Icon\` substitutes a token
 * colour because \`<svg content>\` cannot read CSS variables.
 *
 * Every weight listed for an icon is one some React component actually draws it
 * with; \`regular\` is always present as the default.
 *
 * The artwork is \`@phosphor-icons/core\`, MIT, Copyright (c) 2023 Phosphor Icons
 * (https://github.com/phosphor-icons/core).
 */
export type IconWeight = ${WEIGHTS.map((weight) => `"${weight}"`).join(" | ")};

/** The React component names of every icon the port draws. */
export const iconNames = ${JSON.stringify(names)} as const;

export type IconName = (typeof iconNames)[number];

export const PHOSPHOR: Record<IconName, Partial<Record<IconWeight, string>>> = {
${entries.join("\n")}
};
`;

await Bun.write(`${pkg}/src/icons/phosphor.g.ts`, content);
console.log(`wrote src/icons/phosphor.g.ts: ${names.length} icons, ${entries.length} glyph sets`);
