/**
 * Regenerates the two files nobody hand-edits:
 *
 * - `src/index.ts` — the barrel: one `export * from "./components/<slug>";` per
 *   component file, sorted, followed by the hooks, provider, icons and lib
 *   exports that mirror `@horon-ai/react`'s own barrel tail.
 * - `example/registry.g.ts` — the gallery registry: a sorted list of
 *   `{ slug, load }` entries, one per component file.
 *
 *   bun scripts/integrate.ts           # write
 *   bun scripts/integrate.ts --check   # write nothing; exit 1 when a file would change
 *
 * The demo a slug opens is `example/demos/<slug>.tsx`; a slug whose demo does
 * not exist yet still gets a registry entry, because the gallery renders a
 * placeholder for it and the parity gate is what tracks completion.
 */
const pkg = `${import.meta.dir}/..`;
const componentsDir = `${pkg}/src/components`;
const demosDir = `${pkg}/example/demos`;
const BARREL = `${pkg}/src/index.ts`;
const REGISTRY = `${pkg}/example/registry.g.ts`;

const check = process.argv.includes("--check");

const slugs = [...new Bun.Glob("*.tsx").scanSync(componentsDir)].map((file) => file.replace(/\.tsx$/, "")).toSorted();

/**
 * Only a slug that has both a component and a demo is registered: a static
 * import of a missing module would break the build, and the gallery's job is to
 * show what exists. Re-run this script whenever a lane lands a demo.
 */
const demoSlugs = new Set(
  [...new Bun.Glob("*.tsx").scanSync(demosDir)]
    .map((file) => file.replace(/\.tsx$/, ""))
    .filter((slug) => slugs.includes(slug)),
);

const registered = slugs.filter((slug) => demoSlugs.has(slug));
const demoId = (slug: string) => `demo_${slug.replaceAll("-", "_")}`;

const registry = `// Generated by scripts/integrate.ts. Do not edit.

import type { ComponentType } from "@lynx-js/react";
${registered.map((slug) => `import ${demoId(slug)} from "./demos/${slug}";`).join("\n")}

/** One gallery entry: the component's slug and its demo component. */
export type GalleryEntry = {
  /** The component file stem, identical to \`@horon-ai/react\`'s slug. */
  slug: string;
  /** The demo for that slug. */
  Demo: ComponentType;
};

/** Every registered demo, sorted by slug. */
export const registry: GalleryEntry[] = [
${registered.map((slug) => `  { slug: "${slug}", Demo: ${demoId(slug)} },`).join("\n")}
];
`;

const header = `/**
 * Horon Design System for ReactLynx.
 *
 * The same 84 components as \`@horon-ai/react\`, with the same slugs, the same
 * export names, the same variant literals and the same \`@horon-ai/tokens\`
 * values, re-implemented with Lynx elements instead of DOM elements. Design
 * tokens arrive as the Tailwind v3 class names react uses (\`text-label-md\`,
 * \`bg-glass-regular\`, \`rounded-xl\`), so a ported component keeps its class list.
 *
 * Import everything from the barrel, or one component from its subpath:
 *
 * - \`import { Button, Card, Input } from "@horon-ai/lynx"\` re-exports every component.
 * - \`import { Button } from "@horon-ai/lynx/components/button"\` resolves through the
 *   \`./components/*\` export map, which keeps a bundle to the components it uses.
 * - \`import "@horon-ai/lynx/globals.css"\` brings in the tokens and the motion, glass and
 *   veil utilities; \`src/styles/tokens.css\` alone is the variable layer.
 * - \`import preset from "@horon-ai/lynx/tailwind-preset"\` adds the token utilities to a
 *   Tailwind v3 config, beside \`@lynx-js/tailwind-preset\`.
 *
 * Wrap the tree in \`HoronProvider\` for the palette and the platform type board, then
 * read \`useHoronTheme()\` anywhere below it.
 *
 * @packageDocumentation
 */
`;

const barrel = `${header}${slugs.map((slug) => `export * from "./components/${slug}";`).join("\n")}
export * from "./hooks";
export { HoronProvider, useHoronTheme, type ColorScheme, type ColorToken, type HoronProviderProps, type HoronTheme, type ThemePlatform } from "./provider";
export { Icon, PHOSPHOR, iconNames, useIconColor, type IconColor, type IconName, type IconProps, type IconWeight } from "./icons";
export { cn, type ClassValue } from "./lib/cn";
export { evaluateMediaQuery, readViewport, type MediaSnapshot } from "./lib/media";
export {
  detectOs,
  detectRuntime,
  formatShortcut,
  isModKey,
  matchesShortcut,
  readNavigator,
  type Os,
  type PlatformInput,
  type Runtime,
  type RuntimeWindow,
  type ShortcutEvent,
} from "./lib/platform";
export type { ControlSize } from "./lib/size";
`;

const writes: [string, string][] = [
  [BARREL, barrel],
  [REGISTRY, registry],
];

const currentTexts = await Promise.all(
  writes.map(async ([path]) => {
    const file = Bun.file(path);
    return (await file.exists()) ? file.text() : Promise.resolve("");
  }),
);

const pending = writes.filter(([, content], index) => content !== currentTexts[index]);

if (!check) {
  await Promise.all(pending.map(([path, content]) => Bun.write(path, content)));
  for (const [path] of pending) console.log(`wrote ${path.replace(`${pkg}/`, "")}`);
} else {
  for (const [path] of pending) console.error(`would change ${path.replace(`${pkg}/`, "")}`);
}

const demoCount = registered.length;
console.log(`components=${slugs.length} demos=${demoCount} pending_demos=${slugs.length - demoCount}`);

if (check) {
  console.log("(--check: nothing written)");
  if (pending.length > 0) process.exitCode = 1;
}
