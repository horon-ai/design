/**
 * Generates the Lynx token layer from `@horon-ai/tokens`:
 *
 * - `src/styles/tokens.css` — CSS variables for colour, radius, shadow,
 *   typography, glass rim and veil, with the platform typography boards as
 *   `.horon-platform-*` classes.
 * - `tailwind-preset.cjs` — the Tailwind v3 preset whose utility names equal the
 *   `@horon-ai/react` ones (`text-label-md`, `text-text-primary`,
 *   `bg-glass-regular`, `rounded-xl`, `shadow-popover`).
 *
 * Run `bun scripts/generate-tokens.ts`. `test/tokens.test.ts` rebuilds both in
 * memory and fails when the committed files drift.
 */
import {
  darkColors,
  glass,
  lightColors,
  primitives,
  radius,
  shadow,
  textStyles,
  veil,
  type Platform,
} from "@horon-ai/tokens";

const HEADER = "/* Generated by scripts/generate-tokens.ts. Do not edit. */";
const PRESET_HEADER = "// Generated by scripts/generate-tokens.ts. Do not edit.";

/** `0` stays unitless so a reset is not `0px`; everything else is fixed-point px. */
const px = (value: number) => (value === 0 ? "0" : `${Number(value.toFixed(4))}px`);

const WEIGHT: Record<string, number> = { regular: 400, medium: 500, semibold: 600, bold: 700 };

/** Font size, line height, tracking and weight of every text style for one platform. */
const textLines = (platform: Platform): string[] => {
  const lines: string[] = [];
  for (const [name, style] of Object.entries(textStyles)) {
    lines.push(`  --text-${name}: ${px(style.size[platform])};`);
    lines.push(`  --text-${name}--line-height: ${px(style.lineHeight[platform])};`);
    lines.push(`  --text-${name}--letter-spacing: ${style.tracking === 0 ? "0" : `${style.tracking}em`};`);
    lines.push(`  --text-${name}--font-weight: ${WEIGHT[style.weight]};`);
  }
  return lines;
};

const rimLines = (scheme: keyof typeof glass.rim): string[] => [
  `  --glass-rim-top: ${glass.rim[scheme].top};`,
  `  --glass-rim-mid: ${glass.rim[scheme].mid};`,
  `  --glass-rim-bottom: ${glass.rim[scheme].bottom};`,
];

const veilLines = (scheme: keyof typeof veil.scheme): string[] => [
  `  --veil-ring: ${veil.scheme[scheme].ring};`,
  `  --veil-field: ${veil.scheme[scheme].field};`,
  `  --veil-field-focus: ${veil.scheme[scheme].fieldFocus};`,
  `  --veil-field-shadow: ${veil.scheme[scheme].fieldShadow};`,
  `  --veil-overlay: ${veil.scheme[scheme].overlay};`,
  `  --veil-overlay-shadow: ${veil.scheme[scheme].overlayShadow};`,
];

/**
 * The three glass tiers. Lynx 4.0 ships `<blur-view>`, which filters the backdrop
 * on iOS, Android, HarmonyOS and the web engine, so the tiers keep their real
 * translucent values under `.horon-glass-blur`; where the engine cannot filter
 * (the Clay desktop renderer, an older engine) the tier resolves to the
 * frost-safe `glass-fill-frost`, the same degrade `@horon-ai/react` draws under
 * `@supports not (backdrop-filter: blur(1px))`. Keeping the tier names means a
 * ported component keeps its class list either way.
 */
const GLASS_TIERS: Record<string, true> = {
  "glass-clear": true,
  "glass-clear-hover": true,
  "glass-clear-pressed": true,
  "glass-regular": true,
  "glass-thick": true,
};

const colorLine = ([name, value]: [string, string]) =>
  `  --color-${name}: ${GLASS_TIERS[name] ? "var(--color-glass-fill-frost)" : value};`;

/** The real translucent value of a tier, kept beside the frost degrade under its own name. */
const tierLine = ([name, value]: [string, string]) =>
  GLASS_TIERS[name] ? `  --glass-tier-${name.replace("glass-", "")}: ${value};` : undefined;

/** Under `.horon-glass-blur` the tiers read their real value instead of the frost fill. */
const tierSwitch = Object.keys(GLASS_TIERS).map(
  (name) => `  --color-${name}: var(--glass-tier-${name.replace("glass-", "")});`,
);

/** `page` is the Lynx root element, the equivalent of react's `html`. */
function buildTokensCss(): string {
  const light = Object.entries(lightColors).map(colorLine);
  const prims = Object.entries(primitives).map(colorLine);
  const dark = Object.entries(darkColors).map(colorLine);
  const lightTiers = Object.entries(lightColors)
    .map(tierLine)
    .filter((line): line is string => line !== undefined);
  const darkTiers = Object.entries(darkColors)
    .map(tierLine)
    .filter((line): line is string => line !== undefined);

  const lines: string[] = [
    HEADER,
    "",
    "/*",
    " * The Horon tokens as CSS variables. `page` is the Lynx root element; the",
    " * `HoronProvider` root carries `.horon-light`/`.dark` and",
    " * `.horon-platform-web|desktop|mobile` on a nested view.",
    " *",
    " * Glass: Lynx cannot filter a backdrop, so the tiers resolve to the",
    " * frost-safe `glass-fill-frost` — the same degrade react's globals.css applies",
    " * under `@supports not (backdrop-filter: blur(1px))` and",
    " * `prefers-reduced-transparency: reduce`. The rim variables below are kept, so",
    " * the host still reads as a floating surface.",
    " */",
    "",
    "page,",
    ".horon-light {",
    ...light,
    ...prims,
    "",
    ...lightTiers,
    "",
    `  --glass-blur: ${px(glass.blur)};`,
    `  --glass-saturate: ${glass.saturate};`,
    `  --glass-rim-width: ${px(glass.rimWidth)};`,
    `  --glass-rim-mid-stop: ${Number((glass.rimMidStop * 100).toFixed(6))}%;`,
    ...rimLines("light"),
    `  --veil-blur: ${px(veil.blur)};`,
    `  --veil-saturate: ${veil.saturate};`,
    `  --veil-ring-width: ${px(veil.ringWidth)};`,
    ...veilLines("light"),
    "",
    ...Object.entries(radius).map(([name, value]) => `  --radius-${name}: ${px(value)};`),
    "",
    ...Object.entries(shadow).map(([name, value]) => `  --shadow-${name}: ${value};`),
    "",
    '  --font-sans: "Pretendard Variable", Pretendard, system-ui, sans-serif;',
    '  --font-mono: "Geist Mono Variable", "Geist Mono", ui-monospace, monospace;',
    "",
    ...textLines("web"),
    "",
    ...Object.entries(textStyles).flatMap(([name, style]) =>
      "paragraph" in style ? [`  --paragraph-${name}: ${style.paragraph}em;`] : [],
    ),
    "}",
    "",
    ".dark {",
    ...dark,
    "",
    ...darkTiers,
    "",
    ...rimLines("dark"),
    "",
    ...veilLines("dark"),
    "}",
    "",
    "/*",
    " * `LiquidGlass` adds this class when the engine can filter a backdrop through",
    " * `<blur-view>`; without it the tiers keep the frost fill.",
    " */",
    ".horon-glass-blur {",
    ...tierSwitch,
    "}",
    "",
    ".horon-platform-web {",
    ...textLines("web"),
    "}",
    "",
    ".horon-platform-desktop {",
    ...textLines("desktop"),
    "}",
    "",
    ".horon-platform-mobile {",
    ...textLines("mobile"),
    "}",
    "",
  ];
  return lines.join("\n");
}

/** Tailwind theme values that point at the CSS variables above. */
function buildPreset(): string {
  const colors: Record<string, string> = {};
  for (const name of Object.keys(lightColors)) colors[name] = `var(--color-${name})`;
  for (const name of Object.keys(primitives)) colors[name] = `var(--color-${name})`;

  const borderRadius: Record<string, string> = {};
  for (const name of Object.keys(radius)) borderRadius[name] = `var(--radius-${name})`;

  const boxShadow: Record<string, string> = {};
  for (const name of Object.keys(shadow)) boxShadow[name] = `var(--shadow-${name})`;

  const fontSize: Record<string, [string, Record<string, string>]> = {};
  for (const name of Object.keys(textStyles)) {
    fontSize[name] = [
      `var(--text-${name})`,
      {
        lineHeight: `var(--text-${name}--line-height)`,
        letterSpacing: `var(--text-${name}--letter-spacing)`,
        fontWeight: `var(--text-${name}--font-weight)`,
      },
    ];
  }

  const extend = JSON.stringify(
    {
      colors,
      borderRadius,
      boxShadow,
      fontSize,
      fontFamily: { sans: ["var(--font-sans)"], mono: ["var(--font-mono)"] },
    },
    null,
    2,
  );

  return `${PRESET_HEADER}

/**
 * The Horon design tokens as Tailwind v3 utilities. Class names equal
 * \`@horon-ai/react\`'s (\`text-label-md\`, \`text-text-primary\`,
 * \`bg-glass-regular\`, \`rounded-xl\`, \`shadow-popover\`), but every value is a
 * CSS variable from \`src/styles/tokens.css\`, so the scheme and platform classes
 * on the \`HoronProvider\` root switch them at runtime.
 *
 * The radius scale is non-monotonic on purpose (Figma order): \`2xl\` is 16px and
 * \`xl\` is 20px. Never assume name order.
 */
module.exports = {
  theme: {
    extend: ${extend.replaceAll("\n", "\n    ")},
  },
};
`;
}

const files: Record<string, string> = {
  "src/styles/tokens.css": buildTokensCss(),
  "tailwind-preset.cjs": buildPreset(),
};

export { buildPreset, buildTokensCss, files };

if (import.meta.main) {
  const root = `${import.meta.dir}/..`;
  const entries = Object.entries(files);
  await Promise.all(entries.map(([path, content]) => Bun.write(`${root}/${path}`, content)));
  for (const [path, content] of entries) console.log(`wrote ${path} (${content.length} bytes)`);
}
