/**
 * Generates `lib/src/tokens/horon_tokens.g.dart` from
 * `packages/tokens/dist/tokens.json`.
 *
 * The Dart file is committed, because a Flutter app cannot run a Node build
 * step. It is generated rather than hand-written so a palette change in
 * `packages/tokens/src/*.ts` reaches Flutter without anyone copying values, and
 * `generate-tokens.test.mjs` fails when the committed file no longer matches
 * what this script produces.
 *
 * Class and member names match `mobile/lib/src/theme/tokens.dart`, the file the
 * mobile app replaces with this one, so the migration is an import change and
 * nothing else.
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const TOKENS_JSON = fileURLToPath(new URL("../../tokens/dist/tokens.json", import.meta.url));
const DART_OUT = fileURLToPath(new URL("../lib/src/tokens/horon_tokens.g.dart", import.meta.url));

const HEADER = [
  "// AUTO-GENERATED by design/packages/flutter/scripts/generate-tokens.mjs - do not edit.",
  "// Source: design/packages/tokens/src/*.ts -> design/packages/tokens/dist/tokens.json",
].join("\n");

const RAMPS = ["sand", "gold", "green", "red", "blue"];

const RADIUS_ROLES = ["control", "input", "card", "panel", "bubble", "pill"];

/** Which component and Tailwind class each radius role serves. */
const ROLE_DOCS = {
  control: "`button.tsx` `rounded-md` - `radius.md`, 12.",
  input: "`input.tsx` `rounded-sm` - `radius.sm`, 8.",
  card: "`card.tsx` `rounded-md` - `radius.md`, 12.",
  panel: "`dialog.tsx` and `sheet.tsx` `rounded-lg` - `radius.lg`, 14.",
  bubble: "`bubble.tsx` `rounded-lg` - `radius.lg`, 14.",
  pill: "`chip.tsx` `rounded-full` - [HoronRadius.full], 9999.",
};

/** The mobile file names two easings differently from the web keys. */
const EASING_MEMBERS = {
  default: "easingDefault",
  in: "inCubic",
  out: "out",
  inOut: "inOut",
  inStrong: "inStrong",
  outStrong: "outStrong",
  outCubic: "outCubic",
  outQuint: "outQuint",
  inOutStrong: "inOutStrong",
};

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());

const pascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, char) => char.toUpperCase());

/** `2xl` becomes `xl2`, matching the mobile file's `HoronRadius.xl2`. */
const scaleMember = (key) => key.replace(/^(\d+)xl$/, (_, digit) => `xl${digit}`);

const dartDouble = (value) => (Number.isInteger(value) ? `${value}.0` : `${value}`);

const hexByte = (value) => value.toString(16).padStart(2, "0").toUpperCase();

/** `#rrggbb` or `#rrggbbaa` becomes `Color(0xAARRGGBB)`. */
function dartColor(hex) {
  const value = hex.replace("#", "").toUpperCase();
  if (value.length === 6) return `Color(0xFF${value})`;
  if (value.length === 8) return `Color(0x${value.slice(6, 8)}${value.slice(0, 6)})`;
  throw new Error(`generate-tokens: unsupported color "${hex}"`);
}

const alphaByteOf = (hex) => Number.parseInt(hex.replace("#", "").slice(6, 8), 16);

/** The ink colour carrying an alpha byte, for the shadow and scrim overlays. */
function inkWithAlpha(hex, alphaByte) {
  const rgb = hex.replace("#", "").slice(0, 6).toUpperCase();
  return `Color(0x${hexByte(alphaByte)}${rgb})`;
}

const rgbaColor = ({ r, g, b, a }) => `Color(0x${hexByte(Math.round(a * 255))}${hexByte(r)}${hexByte(g)}${hexByte(b)})`;

function constMember(name, value, docLines = []) {
  const doc = docLines.map((line) => `  /// ${line}\n`).join("");
  return `${doc}  static const ${name} = ${value};`;
}

function classOf(name, docLines, members) {
  const doc = docLines.map((line) => (line ? `/// ${line}` : "///")).join("\n");
  const spaced = members.flatMap((member, index) => {
    const startsDoc = member.startsWith("  ///");
    const previous = members[index - 1];
    const needsGap = startsDoc && index > 0 && previous !== "";
    return needsGap ? ["", member] : [member];
  });
  return `${doc}\nabstract final class ${name} {\n${spaced.join("\n")}\n}`;
}

function paletteMembers(palette) {
  const members = [];
  for (const ramp of RAMPS) {
    members.push("");
    for (const [step, hex] of Object.entries(palette[ramp])) {
      members.push(constMember(`${ramp}${step}`, dartColor(hex)));
    }
  }

  members.push("", constMember("inkLight", dartColor(palette.ink.light)));
  members.push(constMember("inkDark", dartColor(palette.ink.dark)));
  members.push("", constMember("accentLight", dartColor(palette.accent.light)));
  members.push(constMember("accentDark", dartColor(palette.accent.dark)));
  return members.slice(1);
}

function boxShadow(layer) {
  const parts = [
    `color: ${rgbaColor(layer.color)}`,
    `offset: Offset(${layer.offsetX}, ${layer.offsetY})`,
    `blurRadius: ${layer.blur}`,
  ];
  if (layer.spread !== 0) parts.push(`spreadRadius: ${layer.spread}`);
  return `BoxShadow(${parts.join(", ")})`;
}

function shadowMember(name, layers) {
  const entries = layers.map(boxShadow);
  const inline = `<BoxShadow>[${entries.join(", ")}]`;
  const fitsOnOneLine = `  static const ${name} = ${inline};`.length <= 120;
  if (entries.length === 1 && fitsOnOneLine) return inline;
  return `<BoxShadow>[\n${entries.map((entry) => `    ${entry},`).join("\n")}\n  ]`;
}

/**
 * The Dart source for one `tokens.json` payload.
 *
 * Pure and synchronous: the drift test builds the same string in memory from
 * the TypeScript sources and compares it byte for byte with the committed file.
 */
export function buildDartTokens(tokens) {
  const { colors, palette, scales, shadow, easing, metrics } = tokens;

  const inkAlpha = alphaByteOf(colors.light.border);
  const scrimAlpha = alphaByteOf(colors.light["glass-fill"]);

  const paletteBlock = [
    ...paletteMembers(palette),
    "",
    constMember("sand1200Shadow", inkWithAlpha(palette.ink.light, inkAlpha)),
    constMember("sand1200Scrim", inkWithAlpha(palette.ink.light, scrimAlpha)),
  ];

  const lightMembers = Object.entries(colors.light).map(([name, hex]) => constMember(camel(name), dartColor(hex)));
  const darkMembers = Object.entries(colors.dark).map(([name, hex]) => constMember(camel(name), dartColor(hex)));

  const spaceMembers = Object.entries(scales.space)
    .toSorted(([left], [right]) => Number.parseFloat(left) - Number.parseFloat(right))
    .map(([key, value]) => constMember(`s${key.replaceAll(".", "_")}`, dartDouble(value)));

  const radiusMembers = Object.entries(scales.radius).map(([key, value]) =>
    constMember(scaleMember(key), dartDouble(value)),
  );

  const roleMembers = RADIUS_ROLES.map((role) => {
    const value = scales.componentRadius[role];
    const rendered = value === 9999 ? "HoronRadius.full" : dartDouble(value);
    return constMember(role, rendered, [ROLE_DOCS[role]]);
  });

  const durationMembers = Object.entries(scales.duration).map(([key, value]) => constMember(key, `${value}`));

  const easingMembers = Object.entries(easing).map(([key, points]) =>
    constMember(EASING_MEMBERS[key], `Cubic(${points.join(", ")})`),
  );

  const fontSizeMembers = Object.entries(scales.fontSize).map(([key, value]) =>
    constMember(scaleMember(key), dartDouble(value)),
  );

  const textMembers = Object.entries(scales.text).map(([key, value]) => constMember(key, dartDouble(value)));

  const weightMembers = Object.entries(scales.fontWeight).map(([key, value]) =>
    constMember(key, `FontWeight.w${value}`),
  );

  const lineHeightMembers = Object.entries(scales.lineHeight).map(([key, value]) =>
    constMember(key, dartDouble(value)),
  );

  const letterSpacingMembers = Object.entries(scales.letterSpacing).map(([key, value]) =>
    constMember(key, dartDouble(value)),
  );

  const shadowMembers = [
    constMember("smElevation", `${shadow.sm.elevation}`),
    constMember("mdElevation", `${shadow.md.elevation}`),
    constMember("lgElevation", `${shadow.lg.elevation}`),
    "",
    constMember("sm", shadowMember("sm", shadow.sm.layers)),
    constMember("md", shadowMember("md", shadow.md.layers)),
    constMember("lg", shadowMember("lg", shadow.lg.layers)),
  ];

  const breakpointMembers = Object.entries(scales.breakpoint).map(([key, value]) =>
    constMember(scaleMember(key), dartDouble(value)),
  );

  const zIndexMembers = Object.entries(scales.zIndex).map(([key, value]) => constMember(key, `${value}`));

  const metricClasses = Object.entries(metrics).map(([slug, members]) =>
    classOf(
      `Horon${pascal(slug)}Metrics`,
      [`Sizes the ${slug} component draws, in logical pixels.`],
      Object.entries(members).map(([name, value]) => constMember(name, dartDouble(value))),
    ),
  );

  const sections = [
    `// Horon design tokens, generated from the web token source. Do not edit: change
// design/packages/tokens/src/*.ts and run \`bun run tokens\` from design/.
//
// Colors are the OKLCH source run through the same conversion as
// design/packages/tokens/src/color.ts \`oklchToHex\`, so web and Flutter read the
// same computed values.`,

    `import 'dart:ui' show Brightness, Color, FontWeight, Offset;

import 'package:flutter/animation.dart' show Cubic;
import 'package:flutter/painting.dart' show BoxShadow;`,

    classOf(
      "HoronPalette",
      [
        "Raw primitive palette from `palette.ts` (`PALETTE`), plus the `INK` and",
        "`ACCENT` anchors for both brightnesses.",
        "",
        "`sand1200Shadow` is the ink at the 12% alpha the border token uses (the",
        "elevation colour); `sand1200Scrim` is the 45% alpha of the light glass fill",
        "(the modal scrim).",
      ],
      paletteBlock,
    ),

    classOf("HoronLightColors", ["Light semantic tokens from `colorTokens.light`."], lightMembers),
    classOf("HoronDarkColors", ["Dark semantic tokens from `colorTokens.dark`."], darkMembers),

    `/// The design ring colour for [brightness]: gold-500 on light, gold-400 on dark.
///
/// \`ColorScheme\` has no ring slot, so a focused field reads it here instead of
/// deriving one.
Color ringColor(Brightness brightness) => brightness == Brightness.dark ? HoronDarkColors.ring : HoronLightColors.ring;`,

    classOf("HoronSpace", ["4px base spacing scale from `space`, in logical pixels."], spaceMembers),
    classOf("HoronRadius", ["Radius scale from `radius`, in logical pixels."], radiusMembers),
    classOf(
      "HoronRadiusRole",
      [
        "Radius by role, from the radius each design component renders.",
        "",
        "`scales.ts` carries a web `radiusRole` map, but the value that reaches a",
        "screen is the Tailwind class on the component, so each member here is named",
        "after the component it serves and the class that component uses. A surface",
        "names a role, never a raw number.",
      ],
      roleMembers,
    ),
    classOf("HoronDuration", ["Motion durations from `duration`, in milliseconds."], durationMembers),
    classOf("HoronEasing", ["Motion easing from `easing.web`, as bezier control points."], easingMembers),
    classOf("HoronFontSize", ["Raw font sizes from `fontSize`, in logical pixels."], fontSizeMembers),
    classOf("HoronText", ["Semantic type scale from `text`, in logical pixels."], textMembers),
    classOf("HoronFontWeight", ["Font weights from `fontWeight`."], weightMembers),
    classOf("HoronLineHeight", ["Line-height multipliers from `lineHeight`."], lineHeightMembers),
    classOf("HoronLetterSpacing", ["Letter spacing from `letterSpacing`, in em."], letterSpacingMembers),
    classOf(
      "HoronShadow",
      [
        "Elevation from `shadow`. `sm`, `md` and `lg` are the CSS box shadows with",
        "numbers instead of a string; the elevation levels are the Android",
        "equivalents of the same rungs.",
      ],
      shadowMembers,
    ),
    classOf("HoronBreakpoint", ["Layout breakpoints from `breakpoint`, in logical pixels."], breakpointMembers),
    classOf("HoronZIndex", ["Stacking order for overlay layers, from `zIndex`."], zIndexMembers),

    `/// Backdrop-blur radius for glass surfaces (\`glassBlur\`), in logical pixels.
const double horonGlassBlur = ${dartDouble(scales.glassBlur)};

/// Backdrop-blur radius for the liquid-glass surface (\`glassLiquidBlur\`), in
/// logical pixels.
const double horonGlassLiquidBlur = ${dartDouble(scales.glassLiquidBlur)};`,

    ...metricClasses,
  ];

  return `${HEADER}\n\n${sections.join("\n\n")}\n`;
}

async function main() {
  const tokens = JSON.parse(await readFile(TOKENS_JSON, "utf8"));
  await mkdir(dirname(DART_OUT), { recursive: true });
  await writeFile(DART_OUT, buildDartTokens(tokens), "utf8");
  console.log(`horon_ui -> ${DART_OUT}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
