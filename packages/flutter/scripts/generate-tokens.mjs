const isNumeric = (part) => /^[0-9]+(\.[0-9]+)?$/.test(part);

const upperFirst = (part) => part.charAt(0).toUpperCase() + part.slice(1).replace(/[^A-Za-z0-9_]/g, "_");

/**
 * 토큰 이름 하나를 Dart 멤버 이름으로 바꿉니다.
 *
 * 문서화된 규칙은 위 머리말에 있습니다. 테스트가 이 함수를 직접 호출하므로 export합니다.
 */
export function memberName(token) {
  let name = "";
  for (const part of token.split("-")) {
    if (isNumeric(part)) {
      const digits = part.replaceAll(".", "_");
      name += /[0-9]$/.test(name) ? `_${digits}` : digits;
    } else {
      name += upperFirst(part);
    }
  }
  const leadingDigits = /^[0-9]+/.exec(name);
  if (leadingDigits) name = `${name.slice(leadingDigits[0].length)}${leadingDigits[0]}`;
  return name.charAt(0).toLowerCase() + name.slice(1);
}

/** `spacing` 키 하나를 Dart 멤버 이름으로 바꿉니다: '1' -> s1, '1.5' -> s1_5. */
export function spaceName(key) {
  return `s${key.replaceAll(".", "_")}`;
}

/** Dart double 리터럴. 정수에도 소수점을 붙여 타입이 double로 남게 합니다. */
const dartDouble = (value) => {
  const text = Number(value.toFixed(6)).toString();
  return text.includes('.') ? text : `${text}.0`;
};

/** CSS 비율 값은 `css.ts`와 같은 6자리로 자릅니다. */
const cssRatio = (value) => Number(value.toFixed(6));

const hexByte = (value) => value.toString(16).padStart(2, "0").toUpperCase();

/** `#rrggbb` 또는 `#rrggbbaa`를 `Color(0xAARRGGBB)`로 씁니다. */
const dartColor = (hex) => {
  const value = hex.replace("#", "").toUpperCase();
  if (value.length === 6) return `Color(0xFF${value})`;
  if (value.length === 8) return `Color(0x${value.slice(6, 8)}${value.slice(0, 6)})`;
  throw new Error(`generate-tokens: unsupported color "${hex}"`);
};

/** `rgba(10, 13, 15, 0.1)` 같은 CSS 색을 `Color(0xAARRGGBB)`로 씁니다. */
const rgbaColor = (value) => {
  const match = /^rgba?\(([^)]+)\)$/.exec(value.trim());
  if (!match) throw new Error(`generate-tokens: unsupported color "${value}"`);
  const [r, g, b, a = 1] = match[1].split(",").map((part) => Number(part.trim()));
  return `Color(0x${hexByte(Math.round(a * 255))}${hexByte(r)}${hexByte(g)}${hexByte(b)})`;
};

/** `0 8px 24px 0 rgba(10, 13, 15, 0.1)`을 `BoxShadow` 인자로 씁니다. */
function boxShadow(css) {
  const match = /^(.*?)\s+(rgba?\(.+\))$/.exec(css.trim());
  if (!match) throw new Error(`generate-tokens: unsupported box shadow "${css}"`);
  const offsets = match[1].split(/\s+/).map((part) => Number(part.replace('px', '')));
  if (offsets.length !== 4 || offsets.some(Number.isNaN)) {
    throw new Error(`generate-tokens: unsupported box shadow "${css}"`);
  }
  const [offsetX, offsetY, blur, spread] = offsets;
  const parts = [
    `color: ${rgbaColor(match[2])}`,
    `offset: Offset(${dartDouble(offsetX)}, ${dartDouble(offsetY)})`,
    `blurRadius: ${dartDouble(blur)}`,
  ];
  if (spread !== 0) parts.push(`spreadRadius: ${dartDouble(spread)}`);
  return `BoxShadow(${parts.join(', ')})`;
}

/** `dart format`이 문서 주석 앞에 빈 줄을 넣으므로 생성 단계에서 먼저 넣어 둡니다. */
function spaceDocs(members) {
  const out = [];
  for (const member of members) {
    const previous = out.at(-1);
    const startsDoc = member.startsWith("  ///");
    const previousIsDoc = previous?.startsWith("  ///") ?? false;
    if (startsDoc && !previousIsDoc && previous !== undefined && previous !== "") out.push("");
    out.push(member);
  }
  return out;
}

/** 클래스 하나를 문서 주석과 멤버 목록으로 씁니다. */
function dartClass({ name, docs, members }) {
  const doc = docs.map((line) => (line ? `/// ${line}` : "///")).join("\n");
  const spaced = spaceDocs(members).join("\n");
  return `${doc}\n${name.startsWith("final class") ? name : `abstract final class ${name}`} {\n${spaced}\n}`;
}

/** 한 줄짜리 `static const` 멤버입니다. */
const constLine = (indent, type, name, value) => `${indent}static const ${type} ${name} = ${value};`;

/** 의미 색 한 벌을 `static const Color` 멤버로 씁니다. */
const colorMembers = (colors) => Object.entries(colors).map(([token, hex]) => `  ${constLine("", "Color", memberName(token), dartColor(hex))}`);

/** 런타임 묶음([HoronColors])의 필드를 참조하는 한 줄입니다. */
const colorArgument = (prefix, token, indent = "    ") => {
  const name = memberName(token);
  return `${indent}${name}: ${prefix}.${name},`;
};

