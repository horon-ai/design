function semanticClasses() {
  const tokens = Object.keys(lightColors);
  const darkTokens = Object.keys(darkColors);
  if (tokens.join(",") !== darkTokens.join(",")) {
    throw new Error("generate-tokens: lightColors와 darkColors의 키가 다릅니다");
  }

  const light = dartClass({
    name: "HoronLightColors",
    docs: ["라이트 밝기의 의미 색입니다. 키는 `color.ts` `lightColors`의 토큰 이름입니다."],
    members: colorMembers(lightColors),
  });

  const dark = dartClass({
    name: "HoronDarkColors",
    docs: ["다크 밝기의 의미 색입니다. 키는 `color.ts` `darkColors`의 토큰 이름입니다."],
    members: colorMembers(darkColors),
  });

  const colors = dartClass({
    name: "final class HoronColors",
    docs: [
      "현재 밝기의 의미 색 묶음입니다.",
      "",
      "[HoronLightColors]와 [HoronDarkColors]를 같은 이름으로 감싸, 컴포넌트가",
      "`HoronTheme.of(context).colors.<이름>` 한 가지 형태로 읽게 합니다.",
    ],
    members: [
      "  /// 모든 의미 색을 받는 생성자입니다.",
      "  const HoronColors({",
      ...tokens.map((token) => `    required this.${memberName(token)},`),
      "  });",
      "",
      "  /// 라이트 밝기의 의미 색입니다.",
      "  static const HoronColors light = HoronColors(",
      ...tokens.map((token) => colorArgument("HoronLightColors", token)),
      "  );",
      "",
      "  /// 다크 밝기의 의미 색입니다.",
      "  static const HoronColors dark = HoronColors(",
      ...tokens.map((token) => colorArgument("HoronDarkColors", token)),
      "  );",
      "",
      ...tokens.flatMap((token) => [
        `  /// \`${token}\` — \`--color-${token}\`.`,
        `  final Color ${memberName(token)};`,
      ]),
      "",
      "  /// [a]와 [b]를 [t]만큼 보간합니다. 밝기 전환 애니메이션에 씁니다.",
      "  static HoronColors lerp(HoronColors a, HoronColors b, double t) {",
      "    return HoronColors(",
      ...tokens.map((token) => {
        const name = memberName(token);
        return `      ${name}: _lerp(a.${name}, b.${name}, t),`;
      }),
      "    );",
      "  }",
      "",
      "  static Color _lerp(Color a, Color b, double t) => Color.lerp(a, b, t)!;",
    ],
  });

  return [light, dark, colors].join("\n\n");
}

