/** 모바일 값 기준으로 `TextStyle` 인자 줄을 만듭니다. */
function textStyleArgs(style, indent) {
  const size = style.size.mobile;
  const [primary, ...fallback] = fontFamily[style.family];
  const fallbackList = `<String>[${fallback.map((family) => `'${family}'`).join(", ")}]`;
  return [
    `${indent}fontFamily: '${primary}',`,
    `${indent}fontFamilyFallback: ${fallbackList},`,
    `${indent}fontSize: ${dartDouble(size)},`,
    `${indent}fontWeight: HoronFontWeight.${style.weight},`,
    `${indent}letterSpacing: ${dartDouble(letterSpacingPx(style))},`,
    `${indent}height: ${dartDouble(lineHeightRatio(style))},`,
  ];
}

/** CSS em 자간을 글자 크기에 곱해 논리 픽셀로 옮깁니다. */
const letterSpacingPx = (style) => Number((style.size.mobile * style.tracking).toFixed(4));

/** Flutter의 `TextStyle.height`는 배수만 받으므로 줄 높이를 글자 크기로 나눕니다. */
const lineHeightRatio = (style) => Number((style.lineHeight.mobile / style.size.mobile).toFixed(4));

