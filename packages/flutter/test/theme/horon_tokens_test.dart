import 'dart:io';

import 'package:flutter/painting.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:horon_ui/src/theme/horon_fonts.dart';
import 'package:horon_ui/src/tokens/horon_tokens.g.dart';

/// 생성된 토큰이 `packages/tokens/src`의 값을 그대로 드러내는지 확인합니다.
///
/// 값이 생성 파일에서 손으로 바뀌면 웹과 Flutter가 같은 화면에서 다른 값을 그립니다.
/// 드리프트 자체는 `scripts/generate-tokens.test.mjs`가 TypeScript 소스와 바이트로
/// 비교해 잡습니다. 여기서는 Flutter 쪽 계약을 확인합니다: 두 밝기가 같은 이름 집합을
/// 갖는지, 알파가 남는지, 타이포·글래스·간격 값이 문서와 맞는지입니다.
void main() {
  final source = File('lib/src/tokens/horon_tokens.g.dart').readAsStringSync();

  /// 클래스 하나의 `static const` 멤버 이름을 꺼냅니다.
  List<String> membersOf(String className) {
    final start = source.indexOf('abstract final class $className {');
    expect(start, greaterThanOrEqualTo(0), reason: '$className 클래스가 없습니다');
    final body = source.substring(start, source.indexOf('\n}', start));
    return RegExp(
      r'^  static const \S+ ([A-Za-z0-9_]+) =',
      multiLine: true,
    ).allMatches(body).map((match) => match.group(1)!).toList();
  }

  /// `HoronColors`의 필드 이름을 꺼냅니다.
  List<String> wrappedFields() {
    final start = source.indexOf('final class HoronColors {');
    final body = source.substring(start, source.indexOf('\n}\n\n/// `scale.ts`', start));
    return RegExp(
      r'^  final Color ([A-Za-z0-9_]+);$',
      multiLine: true,
    ).allMatches(body).map((match) => match.group(1)!).toList();
  }

  group('생성 파일', () {
    test('자동 생성 머리말이 있고 동결 스냅샷을 가리키지 않는다', () {
      expect(source, startsWith('// AUTO-GENERATED by design/packages/flutter/scripts/generate-tokens.mjs'));
      expect(source.contains('// Source: design/packages/tokens/src/'), isTrue);
      expect(source.contains('legacy-tokens'), isFalse);
      expect(source.contains('이름 규칙'), isTrue);
    });

    test('모든 의미 색이 두 밝기에서 같은 이름으로 존재한다', () {
      final light = membersOf('HoronLightColors');
      final dark = membersOf('HoronDarkColors');
      expect(light.length, greaterThan(80));
      expect(light, dark);
      expect(wrappedFields(), light);
      expect(membersOf('HoronPalette'), isNotEmpty);
    });
  });

  group('의미 색', () {
    test('두 밝기의 대표 색이 토큰 값과 같다', () {
      expect(HoronColors.light.bgSurface, const Color(0xFFFFFFFF));
      expect(HoronColors.dark.bgSurface, const Color(0xFF17181A));
      expect(HoronColors.light.textPrimary, const Color(0xFF17181A));
      expect(HoronColors.dark.textPrimary, const Color(0xFFF9FAFB));
      expect(HoronColors.light.interactivePrimary, const Color(0xFF17181A));
      expect(HoronColors.dark.interactivePrimary, const Color(0xFFF9FAFB));
      expect(HoronColors.light.borderDefault, const Color(0xFFE5E6E7));
      expect(HoronColors.dark.borderDefault, const Color(0xFF2A2B2D));
      expect(HoronColors.light.textOnInk, const Color(0xFFFFFFFF));
      expect(HoronColors.dark.surfaceInk, const Color(0xFF2A2B2D));
    });

    test('알파가 있는 토큰은 알파 바이트를 유지한다', () {
      expect(HoronColors.light.bgSurface6, const Color(0x0FFFFFFF));
      expect(HoronColors.dark.bgSurface6, const Color(0x0F17181A));
      expect(HoronColors.light.overlayInk6, const Color(0x0F000000));
      expect(HoronColors.dark.overlayInk6, const Color(0x0FFFFFFF));
      expect(HoronColors.light.accentSky500_18, const Color(0x2E7199B6));
      expect(HoronColors.dark.bgSurface6.a, closeTo(0x0F / 255, 1e-9));
    });
  });

  group('타이포', () {
    const text = HoronTextStyles();

    test('모바일 크기의 13가지 스타일이 토큰 숫자와 같다', () {
      final styles = <String, TextStyle>{
        'display-lg': text.displayLg,
        'display-md': text.displayMd,
        'title-lg': text.titleLg,
        'title-md': text.titleMd,
        'title-sm': text.titleSm,
        'body-lg': text.bodyLg,
        'body-md': text.bodyMd,
        'body-sm': text.bodySm,
        'label-lg': text.labelLg,
        'label-md': text.labelMd,
        'label-sm': text.labelSm,
        'caption': text.caption,
        'code': text.code,
      };
      // 이름 -> (글자 크기, 줄 높이, 자간 em, 굵기). typography.ts의 mobile 값입니다.
      const expectations = <String, (double, double, double, FontWeight)>{
        'display-lg': (36, 44, -0.03, FontWeight.w700),
        'display-md': (30, 36, -0.025, FontWeight.w700),
        'title-lg': (24, 32, -0.02, FontWeight.w600),
        'title-md': (20, 28, -0.015, FontWeight.w600),
        'title-sm': (18, 26, -0.01, FontWeight.w600),
        'body-lg': (17, 28, -0.008, FontWeight.w400),
        'body-md': (16, 26, -0.005, FontWeight.w400),
        'body-sm': (14, 22, -0.002, FontWeight.w400),
        'label-lg': (16, 22, -0.005, FontWeight.w500),
        'label-md': (14, 20, -0.003, FontWeight.w500),
        'label-sm': (12, 16, 0, FontWeight.w500),
        'caption': (12, 18, 0.005, FontWeight.w400),
        'code': (13, 20, 0, FontWeight.w400),
      };

      expect(styles.keys.toSet(), expectations.keys.toSet());
      for (final entry in expectations.entries) {
        final style = styles[entry.key]!;
        final (size, lineHeight, tracking, weight) = entry.value;
        final reason = 'text-${entry.key}';
        expect(style.fontSize, size, reason: reason);
        expect(style.fontWeight, weight, reason: reason);
        expect(style.letterSpacing, closeTo(size * tracking, 0.001), reason: reason);
        expect(style.fontSize! * style.height!, closeTo(lineHeight, 0.02), reason: reason);
      }
    });

    test('패밀리와 대체 목록이 rebuilt 스택과 같다', () {
      expect(text.bodyMd.fontFamily, HoronFont.sans);
      expect(text.bodyMd.fontFamilyFallback, HoronFont.sansFallback);
      expect(text.code.fontFamily, HoronFont.mono);
      expect(text.code.fontFamilyFallback, HoronFont.monoFallback);
      expect(HoronFont.sans, 'Pretendard Variable');
      expect(HoronFont.mono, 'Geist Mono Variable');
      expect(
        const <FontWeight>[
          HoronFontWeight.regular,
          HoronFontWeight.medium,
          HoronFontWeight.semibold,
          HoronFontWeight.bold,
        ],
        <FontWeight>[FontWeight.w400, FontWeight.w500, FontWeight.w600, FontWeight.w700],
      );
    });
  });

  group('글래스', () {
    const glass = HoronGlassTokens();

    test('glass.ts의 값을 그대로 드러낸다', () {
      expect(glass.layerOpacity, 0.5);
      expect(glass.tintColor, const Color(0x1A545454));
      expect(glass.tintBlur, 45);
      expect(glass.innerShadeColor, const Color(0x1A000000));
      expect(glass.innerShadeBlur, 4);
      expect(glass.innerInsetPerPx, closeTo(1 / 14, 1e-6));
      expect(glass.innerInsetMaxY, 6);
      expect(glass.innerInsetMaxX, 5);
      expect(glass.edgeDarkColor, const Color(0xCC000000));
      expect(glass.edgeDarkBlurPerPx, closeTo(4 / 84, 1e-6));
      expect(glass.edgeDarkMaxBlur, 4);
      expect(glass.edgeLightColor, const Color(0xCCFFFFFF));
      expect(glass.edgeLightBlurPerPx, closeTo(1.5 / 84, 1e-6));
      expect(glass.edgeLightMinBlur, 0.75);
      expect(glass.edgeLightMaxBlur, 1.5);
      expect(glass.edgeLightSoftColor, const Color(0x33FFFFFF));
    });

    test('호스트 높이에 따른 블러와 여백이 CSS 규칙과 같다', () {
      // dark edge blur = min(4, 4H / 84)
      expect(glass.edgeDarkBlurFor(32), closeTo(32 * 4 / 84, 0.001));
      expect(glass.edgeDarkBlurFor(200), 4);
      // light edge blur = clamp(0.75, 1.5H / 84, 1.5)
      expect(glass.edgeLightBlurFor(32), 0.75);
      expect(glass.edgeLightBlurFor(84), closeTo(1.5, 0.001));
      expect(glass.edgeLightBlurFor(300), 1.5);
      // inner shade inset = min(H / 14, 6) 세로, min(H / 14, 5) 가로
      expect(glass.innerInsetYFor(32), closeTo(32 / 14, 0.001));
      expect(glass.innerInsetYFor(120), 6);
      expect(glass.innerInsetXFor(120), 5);
      expect(glass.innerInsetXFor(14), closeTo(1, 0.001));
    });
  });

  group('반경·간격·그림자·브레이크포인트', () {
    test('반경 단계가 scale.ts와 같다', () {
      expect(HoronRadius.none, 0);
      expect(HoronRadius.xs, 6);
      expect(HoronRadius.sm, 8);
      expect(HoronRadius.md, 12);
      expect(HoronRadius.lg, 14);
      expect(HoronRadius.xl, 20);
      expect(HoronRadius.xl2, 16);
      expect(HoronRadius.full, 9999);
    });

    test('간격 단계가 Tailwind 단위 4px로 풀린다', () {
      expect(HoronSpace.s0_5, 2);
      expect(HoronSpace.s1, 4);
      expect(HoronSpace.s1_5, 6);
      expect(HoronSpace.s2, 8);
      expect(HoronSpace.s2_5, 10);
      expect(HoronSpace.s3, 12);
      expect(HoronSpace.s3_5, 14);
      expect(HoronSpace.s4, 16);
      expect(HoronSpace.s5, 20);
      expect(HoronSpace.s6, 24);
      expect(HoronSpace.s8, 32);
    });

    test('그림자가 scale.ts의 CSS 그림자와 같다', () {
      expect(HoronShadow.popover, hasLength(1));
      expect(HoronShadow.popover.single.offset, const Offset(0, 8));
      expect(HoronShadow.popover.single.blurRadius, 24);
      expect(HoronShadow.popover.single.color, const Color(0x1A0A0D0F));
      expect(HoronShadow.palette.single.offset, const Offset(0, 16));
      expect(HoronShadow.palette.single.blurRadius, 40);
      expect(HoronShadow.palette.single.color, const Color(0x1F0A0D0F));
    });

    test('브레이크포인트가 md 768, lg 1024다', () {
      expect(HoronBreakpoint.md, 768);
      expect(HoronBreakpoint.lg, 1024);
      expect(HoronBreakpoint.lg, greaterThan(HoronBreakpoint.md));
    });
  });
}
