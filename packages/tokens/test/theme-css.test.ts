import { describe, expect, test } from "bun:test"
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { oklchToHex } from "../src/color"
import { buildThemeCss } from "../src/css"
import { ACCENT, INK, PALETTE } from "../src/palette"
import { colorTokens } from "../src/tokens"

const THEME_CSS_PATH = fileURLToPath(new URL("../theme.css", import.meta.url))

describe("theme.css drift guard", () => {
	test("the committed theme.css is byte-identical to a fresh regeneration", () => {
		const committed = readFileSync(THEME_CSS_PATH, "utf8")
		const regenerated = buildThemeCss()

		expect(regenerated.length).toBeGreaterThan(1000)
		expect(committed).toContain("AUTO-GENERATED by @horon/tokens")
		expect(committed).toContain("--glass-foreground")
		expect(committed).toBe(regenerated)
	})
})

describe("palette value snapshot", () => {
	test("sand is 12 solid + 6 alpha in both modes", () => {
		for (const mode of ["light", "dark"] as const) {
			expect(PALETTE.sand[mode].solid).toHaveLength(12)
			expect(PALETTE.sand[mode].alpha).toHaveLength(6)
		}
	})

	test("gold accent anchor #e0921f is present", () => {
		expect(oklchToHex(ACCENT.light)).toBe("#e0921f")
		expect(oklchToHex(ACCENT.dark)).toBe("#e0921f")
	})

	test("primary resolves to ink and ring resolves to the gold accent", () => {
		expect(colorTokens.light.primary).toBe(INK.light)
		expect(colorTokens.dark.primary).toBe(INK.dark)
		expect(colorTokens.light.ring).toBe(ACCENT.light)
		expect(colorTokens.dark.ring).toBe(ACCENT.dark)
		expect(oklchToHex(INK.light)).toBe("#262626")
		expect(oklchToHex(INK.dark)).toBe("#f3f3f3")
	})
})
