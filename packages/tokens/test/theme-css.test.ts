describe("palette round-trips to the canvas board hex", () => {
  const ramps = PALETTE as Record<string, Record<string, string>>;

  for (const [ramp, steps] of Object.entries(canvasHex)) {
    test(`${ramp} steps match the canvas`, () => {
      for (const [step, hex] of Object.entries(steps)) {
        expect(oklchToHex(ramps[ramp][step])).toBe(hex);
      }
    });
  }
});

describe("semantic colors follow the canvas board", () => {
  const cases: Array<[ColorTokenName, "light" | "dark", string]> = [
    ["background", "light", "#fafafa"],
    ["background", "dark", "#0a0a0a"],
    ["card", "light", "#ffffff"],
    ["card", "dark", "#141414"],
    ["muted-foreground", "light", "#737373"],
    ["border", "light", "#0a0a0a1f"],
    ["border", "dark", "#fafafa1f"],
    ["info", "light", "#3b6db8"],
    ["info", "dark", "#bbd0ec"],
    ["glass-tint", "light", "#0a0a0a0a"],
    ["glass-tint", "dark", "#ffffff0f"],
  ];

  for (const [name, scheme, hex] of cases) {
    test(`${scheme} ${name} = ${hex}`, () => {
      expect(oklchToHex(colorTokens[scheme][name])).toBe(hex);
    });
  }
});

describe("ink and accent anchors", () => {
  test("primary is ink and ring is the gold accent", () => {
    expect(colorTokens.light.primary).toBe(INK.light);
    expect(colorTokens.dark.primary).toBe(INK.dark);
    expect(colorTokens.light.ring).toBe(ACCENT.light);
    expect(colorTokens.dark.ring).toBe(ACCENT.dark);
    expect(oklchToHex(INK.light)).toBe("#0a0a0a");
    expect(oklchToHex(INK.dark)).toBe("#fafafa");
    expect(oklchToHex(ACCENT.light)).toBe("#c98f2b");
    expect(oklchToHex(ACCENT.dark)).toBe("#e3b65f");
  });
});
