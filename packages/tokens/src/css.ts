import { oklchToHex } from "./color"
import { fontFamily, radiusRem } from "./scales"
import { colorTokens, type ColorTokenName } from "./tokens"

/**
 * Renders the Tailwind v4 `@theme` + CSS-variable layer from the token source,
 * so the web side never drifts from what React Native sees.
 */
export function buildThemeCss(): string {
	const names = Object.keys(colorTokens.light) as ColorTokenName[]

	const themeColors = names
		.map((name) => `  --color-${name}: var(--${name});`)
		.join("\n")
	const lightVars = names
		.map((name) => `  --${name}: ${colorTokens.light[name]};`)
		.join("\n")
	const darkVars = names
		.map((name) => `  --${name}: ${colorTokens.dark[name]};`)
		.join("\n")

	return `/* AUTO-GENERATED by @horon/tokens — do not edit by hand.
 * Source: packages/tokens/src/tokens.ts + src/scales.ts
 * Regenerate: bun run --filter @horon/tokens build
 */

@theme inline {
${themeColors}
  --font-sans: ${fontFamily.sans};
  --font-heading: var(--font-sans);
  --radius-xs: calc(var(--radius) * 0.4);
  --radius-sm: calc(var(--radius) * 0.6);
  --radius-md: calc(var(--radius) * 0.8);
  --radius-lg: var(--radius);
  --radius-xl: calc(var(--radius) * 1.4);
  --radius-2xl: calc(var(--radius) * 1.8);
  --radius-3xl: calc(var(--radius) * 2.2);
  --radius-4xl: calc(var(--radius) * 2.6);
}

:root {
${lightVars}
  --radius: ${radiusRem}rem;
}

.dark {
${darkVars}
}
`
}

/** Hex form of a single token, for React Native. */
export function tokenToHex(name: ColorTokenName, scheme: "light" | "dark") {
	return oklchToHex(colorTokens[scheme][name])
}
