/**
 * Regenerates the three files nobody hand-edits:
 *
 * - `src/index.ts` — the barrel: one `export * from "./components/<slug>";` per
 *   component file, sorted, followed by the hooks, provider and lib exports that
 *   mirror `@horon-ai/react`'s own barrel tail.
 * - `test/pending.ts` — the React slugs with no Expo component yet.
 * - `apps/expo-gallery/registry.g.ts` — the gallery registry, one entry per slug
 *   that has both a component and a demo (`apps/expo-gallery/demos/<slug>.tsx`).
 *
 *   bun scripts/integrate.ts           # write
 *   bun scripts/integrate.ts --check   # write nothing; exit 1 when a file would change
 */
const pkg = `${import.meta.dir}/..`;
const componentsDir = `${pkg}/src/components`;
const gallery = `${pkg}/../../apps/expo-gallery`;
const demosDir = `${gallery}/demos`;
const BARREL = `${pkg}/src/index.ts`;
const REGISTRY = `${gallery}/registry.g.ts`;
const PENDING = `${pkg}/test/pending.ts`;
const reactDir = `${pkg}/../react/src/components`;

const check = process.argv.includes("--check");

const stems = (dir: string) =>
  [...new Bun.Glob("*.tsx").scanSync(dir)].map((file) => file.replace(/\.tsx$/, "")).toSorted();

const slugs = stems(componentsDir);
const demoSlugs = new Set(stems(demosDir));
const registered = slugs.filter((slug) => demoSlugs.has(slug));
const reactSlugs = stems(reactDir);
const missing = reactSlugs.filter((slug) => !slugs.includes(slug));

const pendingFile = `/**
 * Slugs that exist in \`@horon-ai/react\` but have no Expo component yet.
 *
 * The parity gate compares the React component directory against the Expo one
 * and requires the difference to be exactly this list. \`scripts/integrate.ts\`
 * rewrites it from the two directories, so the ledger cannot drift.
 *
 * ${missing.length === 0 ? "Every React slug now has an Expo component." : `${missing.length} of ${reactSlugs.length} React slugs are still unported.`}
 */
export const pendingComponents: readonly string[] = [
${missing.map((slug) => `  "${slug}",`).join("\n")}
];
`;

const demoId = (slug: string) => `demo_${slug.replaceAll("-", "_")}`;

const registry = `// Generated by packages/expo/scripts/integrate.ts. Do not edit.

import type { ComponentType } from "react";
${registered.map((slug) => `import ${demoId(slug)} from "./demos/${slug}";`).join("\n")}

/** One gallery entry: the component's slug and its demo component. */
export type GalleryEntry = {
  /** The component file stem, identical to \`@horon-ai/react\`'s slug. */
  slug: string;
  /** The demo for that slug. */
  Demo: ComponentType;
};

/** Every registered demo, sorted by slug. */
export const registry: GalleryEntry[] = [
${registered.map((slug) => `  { slug: "${slug}", Demo: ${demoId(slug)} },`).join("\n")}
];
`;

const header = `/**
 * Horon Design System for Expo (React Native).
 *
 * The same 84 components as \`@horon-ai/react\`, with the same slugs, the same
 * export names, the same variant literals and the same \`@horon-ai/tokens\`
 * values, re-implemented with React Native views. Colours, type, radius and
 * shadows are read from the tokens at render time through \`useHoronTheme()\`;
 * glass is \`expo-glass-effect\` and safe areas come from
 * \`react-native-safe-area-context\`.
 *
 * - \`import { Button, Card, Input } from "@horon-ai/expo"\` re-exports every component.
 * - \`import { Button } from "@horon-ai/expo/components/button"\` resolves one file.
 *
 * Wrap the tree in \`SafeAreaProvider\` and then \`HoronProvider\`.
 *
 * @packageDocumentation
 */
`;

const barrel = `${header}${slugs.map((slug) => `export * from "./components/${slug}";`).join("\n")}
export * from "./hooks";
export {
  HoronProvider,
  useHoronTheme,
  type ColorScheme,
  type ColorToken,
  type GlassMode,
  type HoronProviderProps,
  type HoronTheme,
  type TextStyleName,
  type ThemePlatform,
  type ThemeTextStyle,
} from "./provider";
export { GlassSurface, type GlassSurfaceProps, type GlassTier } from "./lib/glass-surface";
export { nativeGlassAvailable } from "./lib/glass-support";
export { useInsets } from "./lib/insets";
export { duration, easing } from "./lib/motion";
export {
  detectOs,
  detectRuntime,
  formatShortcut,
  isModKey,
  matchesShortcut,
  type Os,
  type PlatformInput,
  type Runtime,
  type RuntimeWindow,
  type ShortcutEvent,
} from "./lib/platform";
export { HoronPressable, useHaptic, type HoronPressableProps, type PressHaptic } from "./lib/press";
export { controlHeight, touchSlop, TOUCH_TARGET, DISABLED_OPACITY, type ControlSize } from "./lib/size";
export { HoronText, type HoronTextProps } from "./lib/text";
`;

const writes: [string, string][] = [
  [BARREL, barrel],
  [REGISTRY, registry],
  [PENDING, pendingFile],
];

const currentTexts = await Promise.all(
  writes.map(async ([path]) => {
    const file = Bun.file(path);
    return (await file.exists()) ? file.text() : "";
  }),
);

const changed = writes.filter(([, content], index) => content !== currentTexts[index]);

if (check) {
  for (const [path] of changed) console.error(`would change ${path.replace(`${pkg}/`, "")}`);
  if (changed.length > 0) process.exitCode = 1;
} else {
  await Promise.all(changed.map(([path, content]) => Bun.write(path, content)));
  for (const [path] of changed) console.log(`wrote ${path.replace(`${pkg}/`, "")}`);
}

console.log(`components=${slugs.length} demos=${registered.length} pending=${missing.length}`);
